CREATE TABLE Districts (
    DistrictID int IDENTITY(1,1) PRIMARY KEY,
    Name nvarchar(100) NOT NULL UNIQUE
);

CREATE TABLE Streets (
    StreetID int IDENTITY(1,1) PRIMARY KEY,
    Name nvarchar(100) NOT NULL UNIQUE,
    DistrictID int NOT NULL REFERENCES Districts(DistrictID)
);

CREATE TABLE AccidentTypes (
    TypeID int IDENTITY(1,1) PRIMARY KEY,
    Name nvarchar(100) NOT NULL UNIQUE,
    NormHours int NOT NULL CHECK (NormHours > 0)
);

CREATE TABLE Brigades (
    BrigadeID int IDENTITY(1,1) PRIMARY KEY,
    Name nvarchar(100) NOT NULL UNIQUE,
    Phone nvarchar(20) NOT NULL
);

CREATE TABLE Employees (
    EmployeeID int IDENTITY(1,1) PRIMARY KEY,
    FullName nvarchar(150) NOT NULL,
    Position nvarchar(100) NOT NULL,
    Phone nvarchar(20) NULL,
    BrigadeID int NULL REFERENCES Brigades(BrigadeID)
);

CREATE TABLE Materials (
    MaterialID int IDENTITY(1,1) PRIMARY KEY,
    Name nvarchar(150) NOT NULL UNIQUE,
    Unit nvarchar(20) NOT NULL,
    Price decimal(10,2) NOT NULL CHECK (Price >= 0)
);

CREATE TABLE Users (
    UserID int IDENTITY(1,1) PRIMARY KEY,
    Login nvarchar(50) NOT NULL UNIQUE,
    PasswordHash varbinary(32) NOT NULL,
    FullName nvarchar(150) NOT NULL,
    Role nvarchar(20) NOT NULL CHECK (Role IN (N'Администратор', N'Диспетчер', N'Мастер')),
    BrigadeID int NULL REFERENCES Brigades(BrigadeID),
    IsActive bit NOT NULL DEFAULT 1
);

CREATE TABLE Requests (
    RequestID int IDENTITY(1,1) PRIMARY KEY,
    CreatedAt datetime NOT NULL DEFAULT GETDATE(),
    ApplicantName nvarchar(150) NOT NULL,
    ApplicantPhone nvarchar(20) NOT NULL,
    StreetID int NOT NULL REFERENCES Streets(StreetID),
    House nvarchar(10) NOT NULL,
    TypeID int NOT NULL REFERENCES AccidentTypes(TypeID),
    Priority nvarchar(20) NOT NULL CHECK (Priority IN (N'Аварийная', N'Срочная', N'Плановая')),
    Description nvarchar(500) NOT NULL,
    Status nvarchar(20) NOT NULL DEFAULT N'Новая' CHECK (Status IN (N'Новая', N'В работе', N'Выполнена', N'Отменена')),
    BrigadeID int NULL REFERENCES Brigades(BrigadeID),
    DispatcherID int NOT NULL REFERENCES Users(UserID),
    AssignedAt datetime NULL,
    ClosedAt datetime NULL,
    Result nvarchar(500) NULL,
    CHECK (ClosedAt IS NULL OR ClosedAt >= CreatedAt),
    CHECK ((Status = N'Выполнена' AND ClosedAt IS NOT NULL) OR (Status <> N'Выполнена' AND ClosedAt IS NULL))
);

CREATE INDEX IX_Requests_CreatedAt ON Requests(CreatedAt);
CREATE INDEX IX_Requests_Status ON Requests(Status);
CREATE INDEX IX_Requests_BrigadeID ON Requests(BrigadeID);

CREATE TABLE RequestMaterials (
    RequestID int NOT NULL REFERENCES Requests(RequestID) ON DELETE CASCADE,
    MaterialID int NOT NULL REFERENCES Materials(MaterialID),
    Quantity decimal(10,2) NOT NULL CHECK (Quantity > 0),
    Price decimal(10,2) NOT NULL CHECK (Price >= 0),
    PRIMARY KEY (RequestID, MaterialID)
);

CREATE TABLE Shutdowns (
    ShutdownID int IDENTITY(1,1) PRIMARY KEY,
    RequestID int NOT NULL UNIQUE REFERENCES Requests(RequestID) ON DELETE CASCADE,
    StreetID int NOT NULL REFERENCES Streets(StreetID),
    Houses nvarchar(200) NOT NULL,
    StartAt datetime NOT NULL,
    EndAt datetime NOT NULL,
    CHECK (EndAt > StartAt)
);
GO

CREATE VIEW RequestsView AS
SELECT r.RequestID, r.CreatedAt, r.ApplicantName, r.ApplicantPhone,
       s.Name + N', ' + r.House AS Address, s.StreetID, s.Name AS Street,
       d.DistrictID, d.Name AS District, t.Name AS AccidentType,
       r.Priority, r.Status, r.BrigadeID, b.Name AS Brigade,
       u.FullName AS Dispatcher, r.ClosedAt,
       CASE WHEN r.Status IN (N'Новая', N'В работе') AND DATEADD(HOUR, t.NormHours, r.CreatedAt) < GETDATE()
            THEN 1 ELSE 0 END AS Overdue
FROM Requests r
JOIN Streets s ON s.StreetID = r.StreetID
JOIN Districts d ON d.DistrictID = s.DistrictID
JOIN AccidentTypes t ON t.TypeID = r.TypeID
JOIN Users u ON u.UserID = r.DispatcherID
LEFT JOIN Brigades b ON b.BrigadeID = r.BrigadeID;
GO

CREATE PROCEDURE ReportByTypeAndDistrict
    @DateFrom date,
    @DateTo date
AS
SELECT d.Name AS [Район],
       t.Name AS [Тип аварии],
       COUNT(*) AS [Выполнено заявок],
       CAST(AVG(DATEDIFF(MINUTE, r.CreatedAt, r.ClosedAt) / 60.0) AS decimal(6,1)) AS [Среднее время, ч],
       t.NormHours AS [Норматив, ч],
       SUM(CASE WHEN DATEDIFF(MINUTE, r.CreatedAt, r.ClosedAt) > t.NormHours * 60 THEN 1 ELSE 0 END) AS [Сверх норматива],
       CAST(100.0 * SUM(CASE WHEN DATEDIFF(MINUTE, r.CreatedAt, r.ClosedAt) > t.NormHours * 60 THEN 1 ELSE 0 END) / COUNT(*) AS decimal(5,1)) AS [Доля просрочки, %]
FROM Requests r
JOIN Streets s ON s.StreetID = r.StreetID
JOIN Districts d ON d.DistrictID = s.DistrictID
JOIN AccidentTypes t ON t.TypeID = r.TypeID
WHERE r.Status = N'Выполнена'
  AND r.CreatedAt >= @DateFrom AND r.CreatedAt < DATEADD(DAY, 1, @DateTo)
GROUP BY d.Name, t.Name, t.NormHours
ORDER BY d.Name, [Выполнено заявок] DESC;
GO

CREATE PROCEDURE ReportTopStreets
    @DateFrom date,
    @DateTo date
AS
WITH RequestCost AS (
    SELECT RequestID, SUM(Quantity * Price) AS Total
    FROM RequestMaterials
    GROUP BY RequestID
)
SELECT TOP (10)
       RANK() OVER (ORDER BY COUNT(*) DESC) AS [Место],
       s.Name AS [Улица],
       d.Name AS [Район],
       COUNT(*) AS [Аварий],
       SUM(CASE WHEN r.Priority = N'Аварийная' THEN 1 ELSE 0 END) AS [Из них аварийных],
       ISNULL(SUM(c.Total), 0) AS [Затраты на материалы, руб.],
       MAX(r.CreatedAt) AS [Последняя заявка]
FROM Requests r
JOIN Streets s ON s.StreetID = r.StreetID
JOIN Districts d ON d.DistrictID = s.DistrictID
LEFT JOIN RequestCost c ON c.RequestID = r.RequestID
WHERE r.Status <> N'Отменена'
  AND r.CreatedAt >= @DateFrom AND r.CreatedAt < DATEADD(DAY, 1, @DateTo)
GROUP BY s.Name, d.Name
ORDER BY [Аварий] DESC, [Затраты на материалы, руб.] DESC;
GO

CREATE PROCEDURE ReportBrigades
    @DateFrom date,
    @DateTo date
AS
SELECT b.Name AS [Бригада],
       (SELECT COUNT(*) FROM Employees e WHERE e.BrigadeID = b.BrigadeID) AS [Сотрудников],
       SUM(CASE WHEN r.Status = N'Выполнена' THEN 1 ELSE 0 END) AS [Выполнено],
       SUM(CASE WHEN r.Status IN (N'Новая', N'В работе') THEN 1 ELSE 0 END) AS [В работе сейчас],
       CAST(ISNULL(SUM(CASE WHEN r.Status = N'Выполнена' THEN DATEDIFF(MINUTE, r.AssignedAt, r.ClosedAt) END), 0) / 60.0 AS decimal(8,1)) AS [Отработано, ч],
       CAST(AVG(CASE WHEN r.Status = N'Выполнена' THEN DATEDIFF(MINUTE, r.AssignedAt, r.ClosedAt) / 60.0 END) AS decimal(6,1)) AS [Среднее на заявку, ч],
       ISNULL(SUM(m.Total), 0) AS [Материалы, руб.]
FROM Brigades b
LEFT JOIN Requests r ON r.BrigadeID = b.BrigadeID
    AND r.CreatedAt >= @DateFrom AND r.CreatedAt < DATEADD(DAY, 1, @DateTo)
LEFT JOIN (SELECT RequestID, SUM(Quantity * Price) AS Total FROM RequestMaterials GROUP BY RequestID) m
    ON m.RequestID = r.RequestID
GROUP BY b.BrigadeID, b.Name
ORDER BY [Выполнено] DESC;
GO

CREATE PROCEDURE ReportByMonth
    @DateFrom date,
    @DateTo date
AS
SELECT FORMAT(r.CreatedAt, 'yyyy-MM') AS [Месяц],
       COUNT(*) AS [Всего заявок],
       SUM(CASE WHEN t.Name LIKE N'Порыв%' THEN 1 ELSE 0 END) AS [Порывы водопровода],
       SUM(CASE WHEN t.Name LIKE N'%канализ%' THEN 1 ELSE 0 END) AS [Канализация],
       SUM(CASE WHEN r.Priority = N'Аварийная' THEN 1 ELSE 0 END) AS [Аварийных],
       CAST(AVG(CASE WHEN r.Status = N'Выполнена' THEN DATEDIFF(MINUTE, r.CreatedAt, r.ClosedAt) / 60.0 END) AS decimal(6,1)) AS [Среднее время устранения, ч]
FROM Requests r
JOIN AccidentTypes t ON t.TypeID = r.TypeID
WHERE r.Status <> N'Отменена'
  AND r.CreatedAt >= @DateFrom AND r.CreatedAt < DATEADD(DAY, 1, @DateTo)
GROUP BY FORMAT(r.CreatedAt, 'yyyy-MM')
ORDER BY [Месяц];
GO

